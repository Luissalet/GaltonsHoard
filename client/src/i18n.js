export function initialLang() {
  try {
    const saved = localStorage.getItem("galton-lang");
    if (saved === "es" || saved === "en") return saved;
  } catch {
    // storage may be blocked; Spanish is the default
  }
  return "es";
}

export function saveLang(lang) {
  try {
    localStorage.setItem("galton-lang", lang);
  } catch {
    // not critical
  }
}

// A decimal number in a message parameter reads with a comma in Spanish ("0.30" -> "0,30").
const localNumber = (value, index) => (index === 0 && /^-?\d+\.\d+$/.test(String(value)) ? String(value).replace(".", ",") : String(value));

export function makeT(lang) {
  const index = lang === "en" ? 1 : 0;
  const fill = (entry, vars) => {
    let value = entry[index] ?? entry[0];
    if (vars) for (const [name, v] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, localNumber(v, index));
    return value;
  };
  const t = (key, vars) => {
    const entry = D[key];
    if (entry === undefined) return key;
    return fill(entry, vars);
  };
  // A message of the backend: a plain string (free text, shown as it is) or { key, params, text } (formatted in the UI language; the
  // English text is the fallback for a key this build does not know). A parameter may itself be a message.
  const msg = (m) => {
    if (m === null || m === undefined || m === "") return "";
    if (typeof m !== "object") return String(m);
    const entry = D[`msg_${m.key}`] ?? D[`err_${m.key}`];
    if (!m.key || entry === undefined) return m.text ?? "";
    const vars = {};
    for (const [name, v] of Object.entries(m.params || {})) vars[name] = v !== null && typeof v === "object" ? msg(v) : v;
    return fill(entry, vars);
  };
  // An error thrown by api.js: the message of its key (a case with several problems lists them), else the English text the server sent.
  const error = (e) => {
    if (!e) return "";
    const entry = e.key ? D[`err_${e.key}`] : undefined;
    if (entry === undefined) return e.message || String(e);
    const vars = { ...(e.params || {}) };
    if (Array.isArray(e.problemItems) && e.problemItems.length) vars.problems = e.problemItems.map(msg).join("; ");
    return fill(entry, vars);
  };
  const hint = (e) => {
    if (!e) return "";
    const entry = e.key ? D[`hint_${e.key}`] : undefined;
    if (entry === undefined) return e.key ? "" : e.hint || "";
    return fill(entry, e.params || {});
  };
  // A notice of the Panel: its kind and parameters in the UI language, the stored English title and body when the kind is unknown.
  const notice = (n) => {
    const title = D[`notice_title_${n.kind}`];
    const body = D[`notice_body_${n.kind}`];
    const vars = n.params || {};
    return { title: title ? fill(title, vars) : n.title, body: body ? fill(body, vars) : n.body };
  };
  return Object.assign(t, { msg, error, hint, notice });
}

